  async get(table, options = {}) {
    // Simulate API delay
    await new Promise(resolve => setTimeout(resolve, 300));
    
    const items = this.data[table] || [];
    const { limit = 100, published = true } = options;
    
    const filtered = published !== null 
      ? items.filter(item => item.published === published)
      : items;
    
    return {
      data: filtered.slice(0, limit),
      total: filtered.length
    };
  },

  async getOne(table, id) {
    await new Promise(resolve => setTimeout(resolve, 200));
    const item = this.data[table]?.find(i => i.id === id);
    if (!item) throw new Error('Not found');
    return item;
  },

  async post(table, data) {
    await new Promise(resolve => setTimeout(resolve, 300));
    const newItem = {
      id: Date.now().toString(),
      ...data,
      created_at: new Date().toISOString()
    };
    this.data[table].push(newItem);
    return newItem;
  },

  async put(table, id, data) {
    await new Promise(resolve => setTimeout(resolve, 300));
    const index = this.data[table].findIndex(i => i.id === id);
    if (index === -1) throw new Error('Not found');
    this.data[table][index] = { ...this.data[table][index], ...data };
    return this.data[table][index];
  },

  async delete(table, id) {
    await new Promise(resolve => setTimeout(resolve, 300));
    const index = this.data[table].findIndex(i => i.id === id);
    if (index === -1) throw new Error('Not found');
    this.data[table].splice(index, 1);
    return true;
  }
